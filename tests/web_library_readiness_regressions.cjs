const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const app=fs.readFileSync('web/app.js','utf8'),html=fs.readFileSync('web/index.html','utf8');
const node=(tag,cls,text='')=>({tag,cls,text,children:[],append(...xs){this.children.push(...xs)}});
const c=vm.createContext({el:node,statusMark:(name,label)=>node('span','status-mark',label)});
vm.runInContext(app.slice(app.indexOf('function meetingReadiness('),app.indexOf('function meetingCard(')),c);
const text=n=>n.text+' '+n.children.map(text).join(' ');
assert.equal(vm.runInContext('meetingReadiness({})',c),null);
assert.match(text(vm.runInContext('meetingReadiness({readiness:{recording:true}})',c)),/Transcription pending/);
assert.match(text(vm.runInContext('meetingReadiness({readiness:{transcript:true}})',c)),/Transcript ready.*No notes yet/);
assert.match(text(vm.runInContext('meetingReadiness({readiness:{transcript:true,notes:true}})',c)),/Notes ready/);
assert(html.indexOf('id="conversation-source"')<html.indexOf('id="conversation-advanced"'));
console.log('Library readiness PASS: completed stages accessible, missing stages visible, source scope retained.');
